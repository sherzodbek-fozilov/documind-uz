"""Fetch real documents listed in data/sources.json, but only those whose terms were checked.

Rules enforced here:
  * Only entries with ``terms.status == "approved"`` are used, and only if
    ``terms.license``, ``terms.checked_by``, ``terms.checked_on`` are filled in.
    "needs review" and "rejected" entries are never downloaded or ingested.
  * A file can come from ``download_url`` (PDF or DOCX only) or be placed by hand at
    ``data/raw/<id>.pdf|.docx``. For a hand-placed file, ``accessed_on`` must be set in
    the registry; for a download it is set to today.
  * The sha256 of every used file is written back to the registry.
  * Politeness: robots.txt of each host is read first and respected (a URL it disallows
    is skipped); requests are made one at a time with a pause between them
    (``--delay``, default 10 s) and a User-Agent that names this project.

Outputs:
  data/raw/<id>.pdf|.docx     the documents (git-ignored)
  data/raw/manifest.jsonl     read by ``documind ingest data/raw`` (synthetic: false)
  docs/data.md                the "Real document sources" table (between markers)

Usage:
  python scripts/fetch_sources.py               # download approved entries, write outputs
  python scripts/fetch_sources.py --no-download # only use files already in data/raw
  python scripts/fetch_sources.py --render-only # only regenerate the docs/data.md table
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import time
import urllib.error
import urllib.request
import urllib.robotparser
from datetime import date
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "data/sources.json"
RAW = ROOT / "data/raw"
DATA_MD = ROOT / "docs/data.md"
BEGIN = "<!-- BEGIN SOURCES (generated by scripts/fetch_sources.py from data/sources.json) -->"
END = "<!-- END SOURCES -->"

STATUSES = {"approved", "needs review", "rejected"}
LANGUAGES = {"uz-Latn", "uz-Cyrl", "ru"}
CONTENT_TYPES = {"application/pdf": ".pdf",
                 "application/vnd.openxmlformats-officedocument.wordprocessingml.document": ".docx"}
SUFFIXES = (".pdf", ".docx")
USER_AGENT = ("documind-uz research fetcher (non-commercial portfolio project; "
              "https://github.com/sherzodbek-fozilov/documind-uz)")


def load_registry(path: Path = REGISTRY) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def validate(registry: dict) -> list[str]:
    """Return a list of problems (empty = valid)."""
    problems = []
    seen = set()
    for i, s in enumerate(registry.get("sources", [])):
        sid = s.get("id") or f"#{i}"
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", s.get("id") or ""):
            problems.append(f"{sid}: id must be lowercase letters, digits and '-'")
        if sid in seen:
            problems.append(f"{sid}: duplicate id")
        seen.add(sid)
        for key in ("title", "language", "kind", "group_id", "terms"):
            if not s.get(key):
                problems.append(f"{sid}: missing {key}")
        if s.get("language") and s["language"] not in LANGUAGES:
            problems.append(f"{sid}: language must be one of {sorted(LANGUAGES)}")
        terms = s.get("terms") or {}
        if terms.get("status") not in STATUSES:
            problems.append(f"{sid}: terms.status must be one of {sorted(STATUSES)}")
        if terms.get("status") == "approved":
            for key in ("license", "checked_by", "checked_on", "url"):
                if not terms.get(key):
                    problems.append(f"{sid}: approved but terms.{key} is empty")
    return problems


def local_file(sid: str, raw: Path) -> Path | None:
    for suffix in SUFFIXES:
        if (raw / f"{sid}{suffix}").exists():
            return raw / f"{sid}{suffix}"
    return None


class Politeness:
    """robots.txt check per host and a minimum pause between consecutive requests."""

    def __init__(self, delay: float):
        self.delay = delay
        self._last = 0.0
        self._robots: dict[str, urllib.robotparser.RobotFileParser] = {}

    def wait(self) -> None:
        pause = self._last + self.delay - time.monotonic()
        if self._last and pause > 0:
            time.sleep(pause)
        self._last = time.monotonic()

    def allowed(self, url: str) -> bool:
        parts = urlsplit(url)
        host = f"{parts.scheme}://{parts.netloc}"
        if host not in self._robots:
            rp = urllib.robotparser.RobotFileParser(f"{host}/robots.txt")
            self.wait()
            try:
                req = urllib.request.Request(f"{host}/robots.txt",
                                             headers={"User-Agent": USER_AGENT})
                with urllib.request.urlopen(req, timeout=30) as resp:
                    body = resp.read().decode("utf-8", "replace")
                    is_robots = resp.headers.get_content_type() == "text/plain"
            except urllib.error.HTTPError as exc:
                body, is_robots = "", False
                if exc.code in (401, 403):  # access to robots.txt denied: assume disallow
                    body, is_robots = "User-agent: *\nDisallow: /", True
            # a missing robots.txt (404, or a redirect to an HTML error page) means no rules
            rp.parse(body.splitlines() if is_robots else [])
            self._robots[host] = rp
        return self._robots[host].can_fetch(USER_AGENT, url)


def download(url: str, dest_stem: Path) -> Path:
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=60) as resp:
        ctype = resp.headers.get_content_type()
        if ctype not in CONTENT_TYPES:
            raise ValueError(f"{url}: unsupported content type {ctype} (need PDF or DOCX)")
        dest = dest_stem.with_suffix(CONTENT_TYPES[ctype])
        dest.write_bytes(resp.read())
    return dest


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def collect(registry: dict, raw: Path, allow_download: bool, today: str,
            polite: Politeness | None = None) -> tuple[list[dict], list[str]]:
    """Return manifest rows for usable approved entries, and log messages. Mutates registry."""
    rows, log = [], []
    polite = polite or Politeness(delay=10.0)
    for s in registry["sources"]:
        status = s["terms"]["status"]
        if status != "approved":
            log.append(f"skip {s['id']}: terms {status}")
            continue
        path = local_file(s["id"], raw)
        if path is not None:
            if not s.get("accessed_on"):
                log.append(f"skip {s['id']}: hand-placed file but accessed_on is empty")
                continue
        elif allow_download and s.get("download_url"):
            if not polite.allowed(s["download_url"]):
                log.append(f"skip {s['id']}: disallowed by robots.txt")
                continue
            raw.mkdir(parents=True, exist_ok=True)
            polite.wait()
            path = download(s["download_url"], raw / s["id"])
            s["accessed_on"] = today
            log.append(f"downloaded {s['id']} -> {path.name}")
        else:
            log.append(f"skip {s['id']}: no file in data/raw and no download_url")
            continue
        digest = sha256(path)
        if s.get("sha256") and s["sha256"] != digest:
            log.append(f"note {s['id']}: content changed since last fetch (sha256 differs)")
        s["sha256"] = digest
        rows.append({"file": path.name, "doc_id": s["id"], "group_id": s["group_id"],
                     "synthetic": False, "source": s.get("download_url") or s["terms"]["url"],
                     "language": s["language"], "kind": s["kind"],
                     "license": s["terms"]["license"], "accessed_on": s["accessed_on"]})
    return rows, log


def render_table(registry: dict, included: set[str]) -> str:
    def cell(value) -> str:
        return str(value).replace("|", "\\|") if value else "—"

    lines = ["| ID | Title | Lang | URL | Terms | License | Terms checked | Accessed | sha256 "
             "| Included |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for s in registry["sources"]:
        t = s["terms"]
        url = s.get("download_url") or s.get("candidate_url")
        if not url:
            url_cell = "—"
        elif s.get("download_url"):
            url_cell = url
        elif s.get("url_verified_on"):
            url_cell = f"{url} (page verified {s['url_verified_on']}; not downloaded)"
        else:
            url_cell = f"{url} (candidate, unverified)"
        checked = f"{t.get('checked_on')} by {t.get('checked_by')}" if t.get("checked_on") else "—"
        lines.append(" | ".join([
            f"| `{s['id']}`", cell(s["title"]), s["language"], cell(url_cell),
            f"**{t['status']}**", cell(t.get("license")), checked, cell(s.get("accessed_on")),
            f"`{s['sha256'][:12]}`" if s.get("sha256") else "—",
            "yes" if s["id"] in included else "no"]) + " |")
    notes = [f"- `{s['id']}`: {s['terms']['notes']}" for s in registry["sources"]
             if s["terms"].get("notes")]
    return "\n".join(lines + ["", "Notes:", *notes])


def update_data_md(text: str, table: str) -> str:
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit(f"source markers not found in {DATA_MD}")
    return pattern.sub(lambda _: f"{BEGIN}\n{table}\n{END}", text)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--no-download", action="store_true")
    ap.add_argument("--render-only", action="store_true")
    ap.add_argument("--delay", type=float, default=10.0,
                    help="seconds between requests to the same site (default 10)")
    args = ap.parse_args()

    registry = load_registry()
    problems = validate(registry)
    if problems:
        raise SystemExit("invalid data/sources.json:\n  " + "\n  ".join(problems))

    included: set[str] = set()
    if not args.render_only:
        rows, log = collect(registry, RAW, not args.no_download, date.today().isoformat(),
                            Politeness(args.delay))
        print("\n".join(log), file=sys.stderr)
        included = {r["doc_id"] for r in rows}
        if rows:
            RAW.mkdir(parents=True, exist_ok=True)
            with (RAW / "manifest.jsonl").open("w", encoding="utf-8") as f:
                for row in rows:
                    f.write(json.dumps(row, ensure_ascii=False) + "\n")
        REGISTRY.write_text(json.dumps(registry, ensure_ascii=False, indent=2) + "\n",
                            encoding="utf-8")
        print(f"{len(rows)} real documents ready in {RAW}")
    elif (RAW / "manifest.jsonl").exists():
        included = {json.loads(line)["doc_id"] for line in
                    (RAW / "manifest.jsonl").read_text(encoding="utf-8").splitlines() if line}
    DATA_MD.write_text(update_data_md(DATA_MD.read_text(encoding="utf-8"),
                                      render_table(registry, included)), encoding="utf-8")


if __name__ == "__main__":
    main()
