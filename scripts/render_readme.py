"""Regenerate the metrics tables in README.md from results/*.json.

Every number in the README comes from a JSON file written by an evaluation script.
A missing file or a missing metric is rendered as "TBD". Never edit the tables by hand:
the block between the BEGIN/END markers is overwritten.

Result file format (written by the eval scripts):
    {
      "metrics": {"recall@1": 0.41, ...},
      "n": 120,                     # number of evaluated items (questions, pages, ...)
      "n_by_metric": {"cer_ru": 8}, # optional per-metric n (e.g. per language subsets)
      "dataset": "...",             # short description of what was evaluated
      "generated_at": "ISO-8601", "git_commit": "...", "script": "..."
    }
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "<!-- BEGIN METRICS (generated by scripts/render_readme.py, do not edit) -->"
END = "<!-- END METRICS -->"

RETRIEVAL_COLUMNS = [("Recall@1", "recall@1"), ("Recall@5", "recall@5"),
                     ("Recall@10", "recall@10"), ("MRR", "mrr")]
# (label, method key); the file is results/retrieval_<key>_<set>.json
RETRIEVAL_ROWS = [
    ("BM25", "bm25"),
    ("multilingual-e5-small (dense)", "e5_small"),
    ("Hybrid BM25 + e5 (RRF)", "hybrid_rrf"),
    ("Hybrid + reranker", "hybrid_rerank"),
    ("Fine-tuned e5-small (dense)", "e5_small_ft"),
    ("Hybrid with fine-tuned e5 (RRF)", "hybrid_rrf_ft"),
]
RETRIEVAL_SETS = [
    ("real", "Retrieval: real documents (test split, main result)"),
    ("synthetic", "Retrieval: SYNTHETIC sanity set (test split, search within the gold "
                  "document; not comparable to the real set)"),
]
OTHER_ROWS = [
    # (label, file, metric key, format)
    ("OCR CER, synthetic scans, uz-Latn", "ocr_synthetic.json", "cer_uz_latn", "pct"),
    ("OCR CER, synthetic scans, uz-Cyrl", "ocr_synthetic.json", "cer_uz_cyrl", "pct"),
    ("OCR CER, synthetic scans, ru", "ocr_synthetic.json", "cer_ru", "pct"),
    ("Citation correctness", "citations.json", "citation_correctness", "pct"),
    ("Answer latency p50, CPU (s)", "latency.json", "p50_seconds", "num"),
]


def _load(results_dir: Path, name: str) -> dict | None:
    path = results_dir / name
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def _fmt(value, kind: str = "num") -> str:
    if value is None:
        return "TBD"
    if kind == "pct":
        return f"{100 * value:.1f}%"
    return f"{value:.3f}"


def _ci(data: dict, key: str) -> str:
    ci = data.get("ci95", {}).get(key)
    return f" ({ci[0]:.2f}–{ci[1]:.2f})" if ci else ""


def render_tables(results_dir: Path) -> str:
    lines: list[str] = []
    for set_key, title in RETRIEVAL_SETS:
        lines += [f"### {title}", "",
                  "| Method | " + " | ".join(c for c, _ in RETRIEVAL_COLUMNS) + " | Questions |",
                  "|---" * (len(RETRIEVAL_COLUMNS) + 2) + "|"]
        for label, method in RETRIEVAL_ROWS:
            data = _load(results_dir, f"retrieval_{method}_{set_key}.json") or {}
            metrics = data.get("metrics", {})
            cells = [_fmt(metrics.get(key)) + (_ci(data, key) if key in metrics else "")
                     for _, key in RETRIEVAL_COLUMNS]
            n = data.get("n")
            lines.append(f"| {label} | " + " | ".join(cells)
                         + f" | {n if n is not None else 'TBD'} |")
        lines.append("")
    lines += ["Values in parentheses: 95% bootstrap confidence interval over questions.", "",
              "### Other measurements", "", "| Measurement | Value | n | Source file |",
              "|---|---|---|---|"]
    for label, fname, key, kind in OTHER_ROWS:
        data = _load(results_dir, fname) or {}
        n = data.get("n_by_metric", {}).get(key, data.get("n"))
        lines.append(f"| {label} | {_fmt(data.get('metrics', {}).get(key), kind)} | "
                     f"{n if n is not None else 'TBD'} | `results/{fname}` |")
    return "\n".join(lines)


def update_readme(readme: Path, results_dir: Path) -> bool:
    text = readme.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit(f"metrics markers not found in {readme}")
    new = pattern.sub(lambda _: f"{BEGIN}\n{render_tables(results_dir)}\n{END}", text)
    changed = new != text
    readme.write_text(new, encoding="utf-8")
    return changed


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--readme", type=Path, default=ROOT / "README.md")
    ap.add_argument("--results", type=Path, default=ROOT / "results")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if README is out of date (for CI)")
    args = ap.parse_args()
    if args.check:
        original = args.readme.read_text(encoding="utf-8")
        update_readme(args.readme, args.results)
        current = args.readme.read_text(encoding="utf-8")
        args.readme.write_text(original, encoding="utf-8")
        if current != original:
            raise SystemExit("README metrics are out of date; run scripts/render_readme.py")
        return
    print("README updated" if update_readme(args.readme, args.results) else "README unchanged")


if __name__ == "__main__":
    main()
