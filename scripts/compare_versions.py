"""Compare two language versions of a lex.uz act article by article.

Articles are aligned by number ("386-modda" / "Статья 386"). For each article two
language-independent signatures are compared:
  * the number of paragraphs (text blocks);
  * the multiset of numbers written in its text (days, percentages, amounts, references
    to other articles), which a faithful translation keeps.
Articles that differ in either, or exist in only one version, are listed: their content
may not correspond (different editions, a missing amendment), so questions about them
should be avoided when labeling. Wording changes without a number change are not found.

The list is written into docs/data.md between markers named after the act.

Usage: python scripts/compare_versions.py data/raw/civil-code-part2-uz.html \
           data/raw/civil-code-part2-ru.html --name civil-code-part2
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from documind.ingestion.lexuz_html import parse_lexuz_html  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DATA_MD = ROOT / "docs/data.md"
_ARTICLE_RE = re.compile(r"^\s*(?:(\d{1,4})\s*-\s*(?:modda|модда)\b|статья\s+(\d{1,4})\b)",
                         re.IGNORECASE)


_NUMBER_RE = re.compile(r"\d+(?:[.,]\d+)?")


def article_signatures(path: Path) -> tuple[dict[int, tuple[int, tuple[str, ...]]], dict]:
    """Per article number: (paragraph count, sorted numbers in its text); page metadata."""
    doc = parse_lexuz_html(path)
    paras: dict[int, int] = {}
    numbers: dict[int, list[str]] = {}
    current: int | None = None
    for block in doc.pages[0].blocks:
        m = _ARTICLE_RE.match(block.text) if block.kind == "heading" else None
        if m:
            current = int(m.group(1) or m.group(2))
            paras.setdefault(current, 0)
            numbers.setdefault(current, [])
        elif block.kind == "heading":
            current = None  # chapter / § heading: following text is not in an article
        elif current is not None:
            paras[current] += 1
            numbers[current] += [x.replace(",", ".") for x in _NUMBER_RE.findall(block.text)]
    return {n: (paras[n], tuple(sorted(numbers[n]))) for n in paras}, doc.meta


def compare(a: dict, b: dict) -> list[tuple[int, str, str]]:
    """Return (article, what differs, detail) for articles that do not correspond."""
    out = []
    for n in sorted(set(a) | set(b)):
        if n not in a or n not in b:
            out.append((n, "missing", "only in " + ("second" if n not in a else "first")))
            continue
        (pa, na), (pb, nb) = a[n], b[n]
        if pa != pb:
            out.append((n, "paragraphs", f"{pa} vs {pb}"))
        elif na != nb:
            only_a = sorted(set(na) - set(nb)) or ["(counts differ)"]
            only_b = sorted(set(nb) - set(na)) or ["(counts differ)"]
            out.append((n, "numbers", f"{', '.join(only_a[:6])} vs {', '.join(only_b[:6])}"))
    return out


def render(meta_a: dict, meta_b: dict, label_a: str, label_b: str, diffs: list,
           n_a: int, n_b: int) -> str:
    lines = [f"Compared {label_a} (edition {meta_a.get('edition')}, {n_a} articles) with "
             f"{label_b} (edition {meta_b.get('edition')}, {n_b} articles): paragraph count "
             f"and numbers in the text, per article. **{len(diffs)} articles differ**; avoid "
             "them when labeling. (Wording changes that keep all numbers are not detected.)"]
    if diffs:
        lines += ["", f"| Article | Differs in | {label_a} vs {label_b} |", "|---|---|---|"]
        lines += [f"| {n} | {what} | {detail} |" for n, what, detail in diffs]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("version_a", type=Path)
    ap.add_argument("version_b", type=Path)
    ap.add_argument("--name", required=True, help="marker name in docs/data.md")
    ap.add_argument("--labels", default="uz-Latn,ru")
    args = ap.parse_args()
    label_a, label_b = args.labels.split(",")
    a, meta_a = article_signatures(args.version_a)
    b, meta_b = article_signatures(args.version_b)
    diffs = compare(a, b)
    table = render(meta_a, meta_b, label_a, label_b, diffs, len(a), len(b))
    begin = f"<!-- BEGIN VERSION DIFF {args.name} (generated by scripts/compare_versions.py) -->"
    end = f"<!-- END VERSION DIFF {args.name} -->"
    text = DATA_MD.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)
    if not pattern.search(text):
        raise SystemExit(f"markers for {args.name} not found in {DATA_MD}")
    DATA_MD.write_text(pattern.sub(lambda _: f"{begin}\n{table}\n{end}", text), encoding="utf-8")
    print(table)


if __name__ == "__main__":
    main()
